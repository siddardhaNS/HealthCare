import { themes } from './index';
import type { ColorTokens, Mode, Theme, ThemeShared } from './types';

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase()).replace(/([a-z])(\d)/g, '$1-$2');

/** Font faces loaded at runtime (next/font) expose these variables; tokens fall back to the CSS stack. */
export const fontFaceVar = (role: keyof ThemeShared['fonts']) => `--hc-face-${role}`;

function colorVars(colors: ColorTokens) {
  return Object.entries(colors).map(([k, v]) => `  --hc-${kebab(k)}: ${v};`);
}

function sharedVars(t: ThemeShared) {
  const out: string[] = [];
  for (const [role, f] of Object.entries(t.fonts)) out.push(`  --hc-font-${role}: var(${fontFaceVar(role as keyof ThemeShared['fonts'])}), ${f.css};`);
  for (const [k, v] of Object.entries(t.radius)) out.push(`  --hc-radius-${kebab(k)}: ${v}px;`);
  for (const [k, v] of Object.entries(t.text)) {
    out.push(`  --hc-text-${kebab(k)}: ${v.size}px;`);
    out.push(`  --hc-leading-${kebab(k)}: ${v.line}px;`);
  }
  out.push(`  --hc-tap-target: ${t.tapTarget}px;`);
  return out;
}

function block(selector: string, lines: string[]) {
  return `${selector} {\n${lines.join('\n')}\n}`;
}

/**
 * Runtime theme CSS. The provider sets data-theme and data-mode on <html>;
 * without data-mode the OS preference picks the variant.
 */
export function themeCss(all: Record<string, Theme> = themes): string {
  const out: string[] = ['/* Generated by @repo/tokens. Do not edit. */'];
  for (const t of Object.values(all)) {
    const isDefault = t.id === 'aurora';
    const sel = (mode: Mode) => `[data-theme="${t.id}"][data-mode="${mode}"]`;
    const root = isDefault ? ':root, ' : '';
    out.push(block(`${root}[data-theme="${t.id}"]`, [...sharedVars(t), ...colorVars(t.colors.dark), '  color-scheme: dark;']));
    out.push(block(sel('light'), [...colorVars(t.colors.light), '  color-scheme: light;']));
    out.push(block(sel('dark'), [...colorVars(t.colors.dark), '  color-scheme: dark;']));
    out.push(
      `@media (prefers-color-scheme: light) {\n${block(
        `${isDefault ? ':root:not([data-mode]), ' : ''}[data-theme="${t.id}"]:not([data-mode])`,
        [...colorVars(t.colors.light), '  color-scheme: light;'],
      )}\n}`,
    );
  }
  return out.join('\n\n') + '\n';
}

/**
 * Tailwind v4 theme: maps semantic roles to utilities (bg-surface,
 * text-text-muted, rounded-card, font-display...). Default palette and fonts
 * are cleared so only semantic tokens exist as utilities.
 */
export function tailwindCss(all: Record<string, Theme> = themes): string {
  const t = Object.values(all)[0]!;
  const lines: string[] = ['  --color-*: initial;', '  --font-*: initial;', '  --radius-*: initial;', '  --color-transparent: transparent;', '  --color-current: currentColor;'];
  for (const k of Object.keys(t.colors.dark)) lines.push(`  --color-${kebab(k)}: var(--hc-${kebab(k)});`);
  for (const role of Object.keys(t.fonts)) lines.push(`  --font-${role}: var(--hc-font-${role});`);
  for (const k of Object.keys(t.radius)) lines.push(`  --radius-${kebab(k)}: var(--hc-radius-${kebab(k)});`);
  for (const k of Object.keys(t.text)) {
    lines.push(`  --text-${kebab(k)}: var(--hc-text-${kebab(k)});`);
    lines.push(`  --text-${kebab(k)}--line-height: var(--hc-leading-${kebab(k)});`);
  }
  lines.push(`  --spacing: ${t.space[1]}px;`);
  lines.push('  --spacing-tap: var(--hc-tap-target);');
  return `/* Generated by @repo/tokens. Do not edit. */\n@import './theme.css';\n\n@theme inline {\n${lines.join('\n')}\n}\n`;
}
